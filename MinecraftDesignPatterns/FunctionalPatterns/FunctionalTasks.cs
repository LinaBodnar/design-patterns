using System;

namespace MinecraftDesignPatterns.FunctionalPatterns;

public static class FunctionalTasks
{
    // =========================================================================
    // 1. Патерн "СТРАТЕГІЯ" (Strategy) у функціональному стилі
    // =========================================================================
    // Замість створення інтерфейсу IAttackStrategy та класів-наслідників,
    // ми передаємо поведінку атаки як лямбду через вбудований делегат Action<string>.
    public static void AttackMob(string mobName, Action<string> attackStrategy)
    {
        attackStrategy(mobName);
    }

    // =========================================================================
    // 2. Патерн "ФАБРИЧНИЙ МЕТОД" (Factory Method) у функціональному стилі
    // =========================================================================
    // Замість створення абстрактних класів-фабрик (наприклад, ToolFactory),
    // ми передаємо саму логіку створення предмета через делегат Func<string>.
    public static string CraftItem(Func<string> itemFactory)
    {
        return itemFactory();
    }

    // =========================================================================
    // 3. Патерн "ДЕКОРАТОР" (Decorator) у функціональному стилі
    // =========================================================================
    // Функціональний декоратор — це функція вищого порядку, яка приймає іншу функцію
    // (базовий інструмент), додає до неї нову логіку й повертає модифіковану функцію.
    public static Func<int, int> CreateEnchantedTool(Func<int, int> baseTool, string enchantmentName, int bonusDamage)
    {
        return (baseDamage) =>
        {
            // Викликаємо базову атаку
            int totalDamage = baseTool(baseDamage);
            Console.WriteLine($"[Декоратор] Накладено чари: {enchantmentName} (+{bonusDamage} до шкоди)");
            return totalDamage + bonusDamage;
        };
    }

    // =========================================================================
    // 4. Патерн "НАВКОЛИШНЄ ВИКОНАННЯ" (Execute Around)
    // =========================================================================
    // Цей патерн використовується для виконання парних дій (відкрити/закрити, підготувати/очистити).
    // У нашому випадку ми безпечно відкриваємо скриню, виконуємо з нею дії (всередині лямбди),
    // і гарантовано закриваємо її, щоб інші гравці на сервері могли нею користуватися.
    public static void UseChest(string chestType, Action chestOperations)
    {
        Console.WriteLine($"\n[Execute Around] >>> Гравець відкриває {chestType} скриню...");
        try
        {
            // Виконуємо корисну роботу, яку передав користувач через лямбду
            chestOperations();
        }
        finally
        {
            // Цей блок виконається завжди, навіть якщо всередині скрині стався збій
            Console.WriteLine($"[Execute Around] <<< Скриню успішно закрито та збережено на сервері.");
        }
    }
}